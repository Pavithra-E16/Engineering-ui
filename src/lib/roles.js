/**
 * Management and the Principal run the institution, so they can create, edit and delete
 * in every module they can see. Read-only by nature: dashboard, reports, AI insight pages
 * and the append-only audit log.
 */
const READ_ONLY_MODULES = new Set(['dashboard', 'reports', 'audit-logs', 'ai-decision', 'ai-hod', 'ai-early-warning']);
for (const r of ['management', 'principal']) {
  for (const m of Object.keys(PERMISSIONS[r])) if (!READ_ONLY_MODULES.has(m)) PERMISSIONS[r][m] = 'edit';
}

export const canAccess = (role, m, need = 'view') => {
  if (!role) return false;
  const a = PERMISSIONS[role]?.[m];
  if (!a) return false;
  return need === 'view' ? true : a === 'edit';
};
/** Roles whose data must be limited to their own / linked students. */
export const isPersonalRole = (r) => r === 'student' || r === 'parent';
/** Roles limited to their department. */
export const isDepartmentRole = (r) => r === 'hod' || r === 'program-coordinator';
