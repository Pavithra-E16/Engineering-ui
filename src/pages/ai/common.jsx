import { Sparkles } from 'lucide-react';
import { AI_CONNECTED } from '../../lib/ai';
import { SimulatedBadge } from '../../components/ui';
export function AiStatus({ simulated }) {
  if (simulated === false)
    return (
      <span className="badge-live">
        <Sparkles className="icon-14" />
        Generated by server-side AI
      </span>
    );
  return <SimulatedBadge />;
}
export function AiNotice({ children }) {
  return (
    <div className="ai-notice">
      <p className="head">
        <Sparkles className="icon-16" />
        {AI_CONNECTED ? 'AI service endpoint configured' : 'No AI model connected'}
        {!AI_CONNECTED && <SimulatedBadge />}
      </p>
      <p className="xs muted">
        {AI_CONNECTED
          ? 'Narrative outputs are generated by the secure server-side function. Scores and indicators below are computed transparently from authorised ERP data.'
          : 'Indicators below are computed from authorised ERP data using transparent rules. Narrative text is a simulated demo produced from templates — not from a language model. Configure VITE_AI_ENDPOINT (see functions/) to enable Gemini.'}
        {children}
      </p>
    </div>
  );
}
